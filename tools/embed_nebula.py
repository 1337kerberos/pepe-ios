#!/usr/bin/env python3
"""Embeds Assets/nebula_still_1024x576.jpg (frame 1 of the nebula loop, made from
out/wip/nebula/nebula_a_still_1920x1080_f1.jpg) into PepePiP/EmbeddedNebula.swift as base64: the still is the
fallback backdrop while the video loads or if playback fails, and must not depend on bundle lookup (LiveContainer)."""
import base64, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
b64 = base64.b64encode((root / "Assets/nebula_still_1024x576.jpg").read_bytes()).decode()
(root / "PepePiP/EmbeddedNebula.swift").write_text(f'''// GENERATED by tools/embed_nebula.py: frame 1 of the nebula loop (Assets/nebula_720.mp4) as a 1024x576 JPEG.
// The video's still fallback; embedded so it never depends on Bundle lookup (LiveContainer).
import UIKit

enum EmbeddedNebula {{
    static let still1024x576 = "{b64}"

    static func still() -> UIImage? {{
        guard let data = Data(base64Encoded: still1024x576) else {{ return nil }}
        return UIImage(data: data)
    }}
}}
''')
print("EmbeddedNebula.swift", len(b64), "base64 chars")
