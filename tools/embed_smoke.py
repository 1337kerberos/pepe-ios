"""PepePiP/EmbeddedSmoke.swift: the baked Mantaflow exhale (six-way lit flipbook atlases) + the baked tip wisp, as base64
PNGs, for the SceneKit port of the Godot smoke card (PepePiP/BakedSmoke.swift). Embedded like the backdrops and sprites
(LiveContainer-proof, no loose files). Sources (half-res, the web page's variants of the Godot atlases):
  side: web/fx/night1/stream_side_{a,b}.half.png + stream_side.half.json  (= retarget_lab/fx/night1 at half res)
  tip : web/fx/stream_tip_{a,b}.half.png + stream_tip.half.json           (= retarget_lab/fx/tip at half res)
If a half file is missing the full-res Godot atlas is downscaled to 2048 px wide here.
`a` = +X,-X,+Y lighting + alpha; `b` = -Y,+Z,-Z lighting (alpha unused). RGB and alpha are independent data, so the app
must never premultiply them: BakedSmoke.swift copies the decoded bytes straight into its own MTLTexture.
Run: python3 ios/tools/embed_smoke.py
"""
import base64, io, json, os, sys
from PIL import Image
IOS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAB = os.environ.get('PEPE_LAB') or os.path.dirname(IOS)
DST = os.path.join(IOS, 'PepePiP', 'EmbeddedSmoke.swift')
SETS = {
    'side': (os.path.join(LAB, 'web/fx/night1'), os.path.join(LAB, 'retarget_lab/fx/night1'), 'stream_side'),
    'tip': (os.path.join(LAB, 'web/fx'), os.path.join(LAB, 'retarget_lab/fx/tip'), 'stream_tip'),
}

def load(half_dir, full_dir, stem, ch):
    hp = os.path.join(half_dir, f'{stem}_{ch}.half.png')
    if os.path.exists(hp):
        return Image.open(hp), json.load(open(os.path.join(half_dir, f'{stem}.half.json'))), hp
    fp = os.path.join(full_dir, f'{stem}_{ch}.png'); img = Image.open(fp)
    meta = json.load(open(os.path.join(full_dir, f'{stem}.json')))
    s = 2048 / img.width
    img = img.resize((2048, round(img.height * s)), Image.LANCZOS); meta['tile'] = [meta['tile'][0] * s, meta['tile'][1] * s]
    return img, meta, fp + ' (downscaled)'

out, metas, total = {}, {}, 0
for kind, (hd, fd, stem) in SETS.items():
    for ch in 'ab':
        img, meta, src = load(hd, fd, stem, ch)
        img = img.convert('RGBA')   # always RGBA: BakedSmoke uploads the raw bytes (no premultiply) into an rgba8Unorm_srgb MTLTexture
        b = io.BytesIO(); img.save(b, 'PNG', optimize=True); data = b.getvalue(); total += len(data)
        out[f'{kind}_{ch}'] = base64.b64encode(data).decode(); metas[kind] = meta
        print(f'{kind}_{ch}: {src} {img.size} {img.mode} -> {len(data)/1e6:.2f} MB png')

with open(DST, 'w') as f:
    f.write('// GENERATED by tools/embed_smoke.py: the baked exhale + tip wisp atlases (half-res six-way flipbooks) for BakedSmoke.swift.\n')
    f.write('// Do not edit; re-run the script. %.1f MB of PNG as base64.\n' % (total / 1e6))
    f.write('import UIKit\n\nenum EmbeddedSmoke {\n')
    for kind, m in metas.items():
        f.write(f'    static let {kind}Meta = (frames: {int(m["frames"])}, cols: {int(m["cols"])}, rows: {int(m["rows"])}, tileW: {float(m["tile"][0])}, tileH: {float(m["tile"][1])}, '
                f'mouthU: {float(m["mouth_u"])}, mouthV: {float(m["mouth_v"])})\n')
    f.write('    static func image(_ name: String) -> UIImage? {\n        guard let b64 = data[name], let d = Data(base64Encoded: b64) else { return nil }\n        return UIImage(data: d)\n    }\n')
    f.write('    private static let data: [String: String] = [\n')
    for k, v in out.items(): f.write(f'        "{k}": "{v}",\n')
    f.write('    ]\n}\n')
print(f'{DST}: {os.path.getsize(DST)/1e6:.2f} MB source, {total/1e6:.2f} MB png')
