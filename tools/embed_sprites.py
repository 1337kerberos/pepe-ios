"""Shared/EmbeddedSprites.swift from Assets/sprites/<state>.png (512x512 transparent, rendered by the sprite job).
Embedding (like EmbeddedBackdrops.swift) is the one path that builds reliably with XcodeGen for BOTH the app and the
widget extension and survives LiveContainer's foreign Bundle.main. Sprites are downscaled to 256x256 (the Island shows
them at <= 64 pt). A state without a PNG is simply absent: the views fall back to an SF Symbol, so the build never breaks.
Run: python3 ios/tools/embed_sprites.py      (re-run whenever the PNGs change; commit the generated file)
"""
import base64, io, os, sys
STATES = ['idle', 'thinking', 'working', 'waiting', 'celebrating', 'failing', 'smoking', 'sleeping']
IOS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(IOS, 'Assets', 'sprites'); DST = os.path.join(IOS, 'Shared', 'EmbeddedSprites.swift')

try:
    from PIL import Image
except ImportError:
    Image = None

entries, missing, total = [], [], 0
for st in STATES:
    p = os.path.join(SRC, st + '.png')
    if not os.path.exists(p): missing.append(st); continue
    data = open(p, 'rb').read()
    if Image is not None:
        img = Image.open(io.BytesIO(data)).convert('RGBA')
        if max(img.size) > 256: img = img.resize((256, 256), Image.LANCZOS)
        b = io.BytesIO(); img.save(b, 'PNG', optimize=True); data = b.getvalue()
    total += len(data)
    entries.append((st, base64.b64encode(data).decode()))

with open(DST, 'w') as f:
    f.write('// GENERATED by tools/embed_sprites.py from Assets/sprites/*.png: 2D Pepe state sprites for the Live Activity /\n')
    f.write('// Dynamic Island (and anything else that wants a 2D Pepe). Missing states fall back to an SF Symbol (PepeSprite.swift).\n')
    f.write('import UIKit\n\nenum EmbeddedSprites {\n    static let states: [String] = [%s]\n' % ', '.join('"%s"' % s for s, _ in entries))
    f.write('    static func image(_ state: String) -> UIImage? {\n        guard let b64 = data[state], let d = Data(base64Encoded: b64) else { return nil }\n        return UIImage(data: d)\n    }\n')
    f.write('    private static let data: [String: String] = [\n')
    for st, b64 in entries: f.write('        "%s": "%s",\n' % (st, b64))
    f.write('    ]\n}\n')
print(f'{DST}: {len(entries)} sprites embedded ({total/1e3:.0f} KB png)' + (f', missing: {missing}' if missing else ''))
